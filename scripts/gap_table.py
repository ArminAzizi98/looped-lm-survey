#!/usr/bin/env python3
"""Render paper/figures/gap_table.tex from gap_map.json (keyword hits) and gap_map_audit.json (manual audit)."""
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
g = json.load((ROOT / "data/corpus/gap_map.json").open())
a = json.load((ROOT / "data/corpus/gap_map_audit.json").open())
rows = sorted([(t, g[t]["count"], a[t]["audited"]) for t in a if not t.startswith("_")], key=lambda x: (x[2], x[1]))
lines = ["% generated by scripts/gap_table.py", "\\begin{tabular}{@{}lrr@{}}", "\\toprule", "Topic & Keyword hits & Audited \\\\", "\\midrule"]
for t, k, au in rows:
    lines.append(t.replace("&", "\\&") + f" & {k} & {au} \\\\")
lines += ["\\bottomrule", "\\end{tabular}"]
(ROOT / "paper/figures/gap_table.tex").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
