#!/usr/bin/env python3
"""Count how many of our core papers each prior survey cites (title match against its full text,
first 60 normalized characters of each title, titles >= 25 chars). Writes data/corpus/coverage_vs_surveys.json
and macros in paper/figures/coverage.tex. Title matching can undercount (line-broken or abbreviated
titles in reference lists), so reported numbers are lower bounds."""
import json, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sq = lambda s: re.sub(r"[^a-z0-9]", "", (s or "").lower())
core = [json.loads(l) for l in (ROOT / "data/corpus/screened.jsonl").open() if l.strip()]
core = [r for r in core if r["decision"] == "C" and r.get("title") and len(sq(r["title"])) >= 25]
srcs = {"covLatentCoT": ROOT / "data/fulltext/2505.16782.txt", "covLatentReasoning": ROOT / "data/fulltext/2507.06203.txt",
        "covImplicit": ROOT / "data/fulltext/2509.02350.txt", "covGithub": ROOT / "data/raw/github_survey_readme.md"}
out = {"nCoreMatchable": len(core)}
for k, p in srcs.items():
    t = sq(p.read_text(errors="ignore"))
    out[k] = sum(1 for r in core if sq(r["title"])[:60] in t)
json.dump(out, (ROOT / "data/corpus/coverage_vs_surveys.json").open("w"), indent=1)
with (ROOT / "paper/figures/coverage.tex").open("w") as fh:
    fh.write("% generated by scripts/coverage_vs_surveys.py\n")
    for k, v in out.items():
        fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(out)
