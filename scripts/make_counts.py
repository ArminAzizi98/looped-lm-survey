#!/usr/bin/env python3
"""Compute corpus/pipeline counts from data files and write paper/figures/counts.tex as macros,
so that every count in the paper is generated from data, never typed by hand.
"""
import json, glob, collections, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def jl(p):
    p = ROOT / p
    return [json.loads(l) for l in p.open() if l.strip()] if p.exists() else []


def main():
    import importlib.util
    spec = importlib.util.spec_from_file_location("ah", ROOT / "scripts/arxiv_harvest.py")
    ah = importlib.util.module_from_spec(spec); spec.loader.exec_module(ah)
    seeds = json.load((ROOT / "data/corpus/seeds.json").open())
    arx = jl("data/corpus/arxiv_candidates.jsonl")
    s2 = jl("data/corpus/s2_snowball.jsonl")
    cand = jl("data/corpus/candidates.jsonl")
    refs = jl("data/corpus/refsnowball_meta.jsonl")
    scr = jl("data/corpus/screened.jsonl")
    gh = (ROOT / "data/raw/github_survey_readme.md").read_text()
    gh_items = len(set(re.findall(r"- \*\*\[(.+?)\]", gh)))
    s2_unique = {(r["paper"].get("externalIds") or {}).get("ArXiv") or r["paper"].get("title") for r in s2}
    dec = collections.Counter(r["decision"] for r in scr)
    dp = ROOT / "data/corpus/dedup_dropped.json"
    uniq = ({r["key"] for r in cand} | {r["key"] for r in refs}) - set(json.load(dp.open()) if dp.exists() else [])
    core = [r for r in scr if r["decision"] == "C"]
    ftd = ROOT / "data/fulltext"
    ft = ({p.stem for p in ftd.glob("*.txt") if p.stat().st_size > 2000} if ftd.exists()
          else {x.replace("/", "_") for x in (ROOT / "data/corpus/fulltext_ids.txt").read_text().split()})
    core_ft = sum(1 for r in core if (r.get("arxiv_id") or "").replace("/", "_") in ft)
    ex = []
    for f in glob.glob(str(ROOT / "data/extract/*.jsonl")):
        if "/assign_" in f or "landmarks_me" in f:
            continue
        ex += [json.loads(l) for l in open(f) if l.strip()]
    ver = {}
    vp = ROOT / "data/extract/verification_report.json"
    if vp.exists():
        ver = json.load(vp.open())
    core_dates = [(r.get("published") or "")[:10] for r in core]
    last12 = sum(1 for d in core_dates if d >= "2025-10-05")
    m_extra = {"nCoreLastYear": last12, "pctCoreLastYear": round(100 * last12 / max(1, len(core)))}
    m = {
        "nPhrases": len(ah.PHRASES), "nQueries": len(ah.PHRASES) * len(ah.FIELDS), "nSeeds": len(seeds),
        "nArxivHits": len(arx), "nSSHits": len(s2_unique), "nGithubItems": gh_items, "nRefSnowball": len(refs),
        "nUnique": len(uniq), "nScreened": len(scr),
        "nCore": dec.get("C", 0), "nCoreArxiv": sum(1 for r in core if r.get("arxiv_id")), "nAdjacent": dec.get("A", 0), "nOut": dec.get("X", 0),
        "nPrescreenDropped": len(uniq) - len(scr),
        "nCoreFulltext": core_ft, "nExtracted": len(ex),
        "nQuotesChecked": ver.get("checked", 0), "nQuotesOK": ver.get("ok", 0),
        "nCodeLinks": sum(1 for r in ex if (r.get("artifacts") or {}).get("code") and r.get("relevance") != "out"),
        "nWeightLinks": sum(1 for r in ex if (r.get("artifacts") or {}).get("weights") and r.get("relevance") != "out"),
    }
    m.update(m_extra)
    with (ROOT / "paper/figures/counts.tex").open("w") as fh:
        fh.write("% generated by scripts/make_counts.py; do not edit by hand\n")
        for k, v in m.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v:,}}}\n".replace(",", "{,}"))
    print(json.dumps(m, indent=1))


if __name__ == "__main__":
    main()
