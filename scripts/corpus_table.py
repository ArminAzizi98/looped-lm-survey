#!/usr/bin/env python3
"""Appendix listing of every core paper by topic (paper/figures/corpus_by_topic.tex). arXiv papers are cited as
ax<id>; non-arXiv papers as nx<hash> when resolved in data/corpus/nonarxiv_meta.json. Papers whose metadata could not
be resolved are counted and left to the released corpus."""
import json, re, hashlib, collections
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
NAMES = {"architecture_topology_sharing": "Architecture, topology and sharing", "adaptive_depth_halting_routing": "Adaptive depth, halting and routing",
 "training_stability_gradients": "Training, stability and gradients", "retrofit_training_free": "Retrofitting and training-free looping",
 "scaling_laws": "Scaling laws", "inference_systems": "Inference systems", "theory_expressivity": "Theory: expressivity",
 "theory_icl_algorithms_optimization": "Theory: in-context learning and optimization", "algorithmic_length_generalization": "Algorithmic and length generalization",
 "mechanisms_interpretability": "Mechanisms and interpretability", "capabilities_lm_evaluation": "Capabilities of looped language models",
 "recursive_reasoning_models": "Recursive reasoning models", "posttraining_rl_distill": "Post-training, reinforcement learning and distillation",
 "lineage_foundations": "Lineage and foundations", "vision": "Vision", "multimodal": "Multimodal models", "speech_audio": "Speech and audio",
 "diffusion_generation_backbones": "Diffusion and generative backbones", "diffusion_lm": "Diffusion language models", "rl_robotics_control": "Reinforcement learning, robotics and control",
 "recsys_retrieval": "Recommendation and retrieval", "science_other_domains": "Science and other domains", "safety_trust": "Safety and trust",
 "survey_position": "Surveys and position papers", "other": "Other"}
norm = lambda t: re.sub(r"[^a-z0-9 ]+", " ", (t or "").lower())
nxkey = lambda t: "nx" + hashlib.sha1(" ".join(norm(t).split()).encode()).hexdigest()[:8]
meta = {}
for f in ["candidates.jsonl", "manual_additions.jsonl", "refsnowball_meta.jsonl"]:
    for l in (ROOT / "data/corpus" / f).open():
        r = json.loads(l)
        if r.get("arxiv_id") and r.get("authors"):
            meta[r["arxiv_id"]] = r
nxm = json.loads((ROOT / "data/corpus/nonarxiv_meta.json").read_text())
scr = [json.loads(l) for l in (ROOT / "data/corpus/screened.jsonl").open()]
core = [r for r in scr if r["decision"] == "C"]
groups = collections.defaultdict(list); unlisted = 0
for r in core:
    if r.get("arxiv_id"):
        if r["arxiv_id"] not in meta:
            unlisted += 1; continue
        k = "ax" + r["arxiv_id"]
    else:
        k = nxkey(r["title"]); e = nxm.get(k)
        if e and str(e.get("duplicate_of", "")).startswith("doi"):
            k = e["duplicate_of"]  # same paper is cited under a curated non-arXiv key
        elif e and e.get("duplicate_of") and e["duplicate_of"] in meta:
            k = "ax" + e["duplicate_of"]  # non-arXiv record of an arXiv paper
        elif not e or not e.get("ok") or e.get("duplicate_of"):
            unlisted += 1; continue
    if any(k == kk for g in groups.values() for _, kk in g):
        continue
    groups[r.get("topic") or "other"].append(((r.get("published") or "")[:10], k))
lines = ["% generated by scripts/corpus_table.py; do not edit by hand"]
total = 0
for t in sorted(groups, key=lambda t: -len(groups[t])):
    ks = [k for _, k in sorted(groups[t])]
    total += len(ks)
    lines.append(f"\\paragraph{{{NAMES.get(t, t.replace('_', ' '))} ({len(ks)}).}} \\citep{{{','.join(ks)}}}\n")
(ROOT / "paper/figures/corpus_by_topic.tex").write_text("\n".join(lines) + "\n")
(ROOT / "paper/figures/corpus_by_topic_counts.tex").write_text(f"\\newcommand{{\\nCorpusListed}}{{{total}}}\n\\newcommand{{\\nCorpusUnlisted}}{{{unlisted}}}\n")
print("listed", total, "unlisted", unlisted, "topics", len(groups))
