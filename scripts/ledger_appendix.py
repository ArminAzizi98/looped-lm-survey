#!/usr/bin/env python3
"""Appendix table: claims-ledger excerpt for priority-1 core papers (up to 2 architecture-comparison
claims per paper), with regime and scale. Writes paper/figures/ledger_excerpt.tex (longtable).
Claim texts are the extraction agents' paraphrases; each is backed by a verified verbatim quote in
data/ledger/claims.csv."""
import csv, collections, re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
ARCH = ["iso_param", "iso_train_flop", "iso_infer_flop", "iso_effective_depth", "iso_data", "unmatched"]
LAB = {"iso_param": "P", "iso_train_flop": "TF", "iso_infer_flop": "IF", "iso_effective_depth": "D", "iso_data": "Dat", "unmatched": "U"}
rows = [r for r in csv.DictReader((ROOT / "data/ledger/claims.csv").open())
        if r["verified"] == "True" and r["relevance"] != "adjacent" and r["priority"] == "1"
        and set(r["regimes"].split(";")) & set(ARCH)]
by = collections.defaultdict(list)
for r in rows:
    by[r["arxiv_id"]].append(r)
def tex(s):
    s = (s or "").replace("\\", " ").replace("&", "\\&").replace("%", "\\%").replace("$", "\\$").replace("#", "\\#").replace("_", "\\_")
    s = s.replace("~", "\\textasciitilde{}").replace("^", "\\textasciicircum{}").replace("<", "$<$").replace(">", "$>$")
    import unicodedata
    MAP = {"⊗": "$\\otimes$", "∼": "$\\sim$", "µ": "$\\mu$", "μ": "$\\mu$", "α": "$\\alpha$", "β": "$\\beta$", "γ": "$\\gamma$",
           "δ": "$\\delta$", "λ": "$\\lambda$", "ρ": "$\\rho$", "σ": "$\\sigma$", "τ": "$\\tau$", "θ": "$\\theta$", "κ": "$\\kappa$",
           "Δ": "$\\Delta$", "±": "$\\pm$", "·": "$\\cdot$", "–": "--", "—": "--", "’": "'", "‘": "'", "“": "``", "”": "''", "…": "...",
           "⌈": "$\\lceil$", "⌉": "$\\rceil$", "⌊": "$\\lfloor$", "⌋": "$\\rfloor$", "∈": "$\\in$", "√": "$\\sqrt{}$", "≠": "$\\neq$", "∞": "$\\infty$"}
    for k, v in MAP.items():
        s = s.replace(k, v)
    s = s.replace("≈", "$\\approx$").replace("×", "$\\times$").replace("→", "$\\to$").replace("≥", "$\\geq$").replace("≤", "$\\leq$").replace("−", "-").replace("φ", "$\\varphi$")
    s = "".join(c if ord(c) < 128 else (unicodedata.normalize("NFKD", c).encode("ascii", "ignore").decode() or "") for c in s)
    return s
out = ["% generated by scripts/ledger_appendix.py", "\\begin{longtable}{@{}>{\\raggedright\\arraybackslash}p{2.7cm}>{\\raggedright\\arraybackslash}p{7.9cm}>{\\raggedright\\arraybackslash}p{1.3cm}>{\\raggedright\\arraybackslash}p{2.5cm}@{}}",
       "\\caption{Claims-ledger excerpt: up to two architecture-comparison claims per priority-1 core paper. Regimes: P matched parameters, D matched effective depth, IF matched inference FLOPs, TF matched training FLOPs, Dat matched data, U unmatched. Claim wording is paraphrased from the extraction records; each is backed by a verified quotation in the released ledger.}\\label{tab:ledger_excerpt}\\\\",
       "\\toprule Paper & Claim & Regime & Scale \\\\ \\midrule \\endfirsthead",
       "\\toprule Paper & Claim & Regime & Scale \\\\ \\midrule \\endhead", "\\bottomrule \\endfoot"]
for aid in sorted(by, key=lambda a: (by[a][0]["short_name"] or by[a][0]["title"] or "").lower()):
    rs = sorted(by[aid], key=lambda r: (r["regimes"] == "unmatched", -len(r["regimes"])))[:2]
    for r in rs:
        reg = ", ".join(LAB[x] for x in r["regimes"].split(";") if x in LAB)
        name = tex(r["short_name"] or "").replace("/", "/\\allowbreak{}") if r["short_name"] not in (None, "", "None") else ""
        cite = f"{name}~\\citep{{ax{aid}}}" if name else f"\\citep{{ax{aid}}}"
        out.append(f"{cite} & {tex(r['claim'])} & {reg} & {tex(r['scale'] or '')} \\\\")
out.append("\\end{longtable}")
(ROOT / "paper/figures/ledger_excerpt.tex").write_text("\n".join(out) + "\n")
print("papers", len(by), "rows", len(out) - 7)
