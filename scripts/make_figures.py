#!/usr/bin/env python3
"""Bibliometric figures from data/corpus/screened.jsonl (core papers only).

fig_growth.pdf : monthly count of core papers, stacked by coarse area, 2023-01 .. snapshot month.
fig_topics.pdf : core papers per topic (horizontal bars), including zero-count gap topics.
Also writes paper/figures/growth_table.tex (the data behind fig_growth, for the appendix).

Palette: the dataviz skill's documented reference categorical palette, light mode, fixed slot order
(blue, orange, aqua, yellow, magenta, green, violet). Stacked bars use the adjacent pairlist, which the
palette documentation reports as passing in light mode. Text uses ink tokens, never series colors.
"""
import json, collections
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT / "paper/figures"
SNAP = "2026-10"

SURFACE = "#fcfcfb"; INK = "#0b0b0b"; INK2 = "#52514e"; GRID = "#e4e3df"
SLOTS = ["#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#e87ba4", "#008300", "#4a3aa7"]

AREAS = [  # (label, topics)
    ("Architecture & adaptive depth", ["lineage_foundations", "architecture_topology_sharing", "adaptive_depth_halting_routing"]),
    ("Training, scaling & systems", ["training_stability_gradients", "retrofit_training_free", "posttraining_rl_distill", "scaling_laws", "inference_systems"]),
    ("Theory & mechanisms", ["theory_expressivity", "theory_icl_algorithms_optimization", "algorithmic_length_generalization", "mechanisms_interpretability"]),
    ("Capabilities & recursive reasoning", ["capabilities_lm_evaluation", "recursive_reasoning_models"]),
    ("Beyond language", ["vision", "speech_audio", "rl_robotics_control", "recsys_retrieval", "science_other_domains", "diffusion_generation_backbones", "multimodal"]),
    ("Safety & other", ["safety_trust", "survey_position", "other", None]),
]
T2A = {t: a for a, ts in AREAS for t in ts}


def months(start, end):
    y, m = map(int, start.split("-")); ey, em = map(int, end.split("-"))
    out = []
    while (y, m) <= (ey, em):
        out.append(f"{y:04d}-{m:02d}"); m += 1
        if m == 13:
            y, m = y + 1, 1
    return out


def style(ax):
    ax.set_facecolor(SURFACE)
    for s in ["top", "right"]:
        ax.spines[s].set_visible(False)
    for s in ["left", "bottom"]:
        ax.spines[s].set_color(INK2); ax.spines[s].set_linewidth(0.6)
    ax.tick_params(colors=INK2, labelsize=9.5, width=0.6)
    ax.grid(axis="y", color=GRID, linewidth=0.6); ax.set_axisbelow(True)


def main():
    core = [json.loads(l) for l in (ROOT / "data/corpus/screened.jsonl").open() if l.strip()]
    core = [r for r in core if r["decision"] == "C" and (r.get("published") or "")[:7] >= "2016-01"]
    ms = months("2023-01", SNAP)
    counts = {a: collections.Counter() for a, _ in AREAS}
    pre = collections.Counter()
    for r in core:
        mo = (r.get("published") or "")[:7]
        a = T2A.get(r.get("topic"), "Safety & other")
        if mo < "2023-01":
            pre[a] += 1
        else:
            counts[a][mo] += 1
    # ---- growth figure
    fig, ax = plt.subplots(figsize=(7.0, 2.6), dpi=200)
    fig.patch.set_facecolor(SURFACE); style(ax)
    bottom = [0] * len(ms)
    for i, (a, _) in enumerate(AREAS):
        vals = [counts[a][m] for m in ms]
        ax.bar(range(len(ms)), vals, bottom=bottom, color=SLOTS[i], width=0.82, label=a,
               edgecolor=SURFACE, linewidth=0.8)
        bottom = [b + v for b, v in zip(bottom, vals)]
    ticks = [i for i, m in enumerate(ms) if m.endswith("-01") or m.endswith("-07")]
    ax.set_xticks(ticks); ax.set_xticklabels([ms[i] for i in ticks])
    ax.set_ylabel("core papers / month", color=INK2, fontsize=9.5)
    ax.set_xlim(-0.7, len(ms) - 0.3)
    leg = ax.legend(loc="upper left", fontsize=8.1, frameon=False, ncol=2)
    for t in leg.get_texts():
        t.set_color(INK)
    fig.tight_layout()
    fig.savefig(FIG / "fig_growth.pdf", facecolor=SURFACE)
    # ---- table behind the figure
    with (FIG / "growth_table.tex").open("w") as fh:
        fh.write("% generated by scripts/make_figures.py\n\\begin{tabular}{l" + "r" * (len(AREAS) + 1) + "}\n\\toprule\nMonth & "
                 + " & ".join(a.replace("&", "\\&") for a, _ in AREAS) + " & Total \\\\\n\\midrule\n")
        fh.write("before 2023 & " + " & ".join(str(pre[a]) for a, _ in AREAS) + f" & {sum(pre.values())} \\\\\n")
        for m in ms:
            row = [counts[a][m] for a, _ in AREAS]
            fh.write(f"{m} & " + " & ".join(map(str, row)) + f" & {sum(row)} \\\\\n")
        fh.write("\\bottomrule\n\\end{tabular}\n")
    # ---- topic counts
    tc = collections.Counter(r.get("topic") for r in core)
    print("core papers since 2016:", len(core))
    print(json.dumps(tc.most_common(), indent=0))


if __name__ == "__main__":
    main()
